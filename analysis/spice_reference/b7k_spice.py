#!/usr/bin/env python3
"""Independent ngspice netlist of the B7K schematic AS DRAWN (primary p.4), for parity checks.

Why this exists
---------------
Every per-stage test in tests/ validates a C++ stage against a closed-form oracle in
analysis/eq_reference.py written from the same reading of the circuit as the C++.  Neither is
independent of the other, and neither says anything about the whole chain.  This module is the
independent leg: a SPICE netlist of the schematic with the DRAWN component values (circuit.md's
tables, spot-checked against the rasterised primary p.4 at 300 DPI on 2026-11-05), solved by
ngspice, which shares no code with the plugin.

Scope / honesty
---------------
* Topology and values are the *original-B7K clone board's* (circuit.md).  The Ultra-only parts
  ([ENG]: MASTER, 3-way ATTACK centre, switchable mid caps, DIST footswitch) are NOT on that
  schematic.  MASTER and the switchable mids are included here exactly as circuit.md specifies
  them so the full signal path can be exercised, and are flagged as [ENG].
* Op-amps are single-pole behavioural models (A0 = 2e5, GBW selectable).  `gbw=None` gives an
  effectively ideal op-amp (what the plugin assumes); gbw=3e6 is the TL07x datasheet typical.
* J201 / CD4049 use the SPICE parameter sets documented in docs/nonlinear-component-modeling.md.
  The J201 has a ~5:1 unit-to-unit spread, so those two blocks are a *typical-part* reference,
  not ground truth for any particular unit.

Pot conventions (match circuit.md / the plugin's knob space):
  EQ pots (Baxandall BASS/TREBLE, LO-MID, HI-MID): knob 1.0 = full boost = wiper at the
  input-side lug (lug 3).  B taper (linear).  knob 0.5 = flat.
  BLEND: knob 0 = 100 % clean (wiper at pin 1), 1 = 100 % OD (wiper at pin 3).  B taper.
  LEVEL / DRIVE / MASTER tapers are *fitted* in the plugin; here they are specified by the
  RESISTANCE they present, so a caller supplies the taper it wants to test.
"""
import os
import re
import shutil
import subprocess
import tempfile

import numpy as np

# --------------------------------------------------------------------------------------------
# Drawn component values (circuit.md tables; verified against the schematic image)
# --------------------------------------------------------------------------------------------
DRAWN = dict(
    # input
    R1=1e6, C1=100e-9, R2=1e6, R3=10e3,
    # JFET stage
    C2=1e-9, R4=100e3, R5=1e6, R6=3.3e3, C3=220e-9, R9=1e6, R10=1e6, C4=22e-9,
    # treble / ATTACK ladder
    R7=200e3, R8=470e3, C5=22e-9, C9=22e-9, C6=22e-9, R12=6.8e3, R14=22e3, C8=220e-12,
    R11=470e3, C7=100e-9, R13=1e6,
    # DRIVE stage
    R15=330e3, C10=47e-12, R17=3.3e3, R32=1e3,
    # GRUNT + clipper
    C11=4.7e-9, C12=47e-9, C13=220e-9, R16=6.8e3, R18=330e3, C14=220e-12, R19=1e3,
    # recovery buffer + bridged-T + Sallen-Keys
    C15=2.2e-6, R20=10e3, R21=1e6, R22=100e3, R23=33e3, C16=680e-12, C17=22e-9,
    R24=10e3, R25=22e3, C27=1e-9, C18=1e-9, R26=22e3, R27=47e3, C20=1e-9, C19=2.2e-9,
    # LEVEL / BLEND pot totals
    Rlevel=100e3, Rblend=100e3,
    # EQ
    R28=10e3, R29=22e3, C21=100e-9, R33=10e3, R34=10e3, C25=22e-9, C26=22e-9, R35=10e3,
    C28=10e-9, C29=10e-9, R36=3.3e3, R37=1e6, C30=47e-12, C31=2.2e-6,
    R38=2.2e3, R39=2.2e3, R40=220e3, R41=220e3, C32=22e-9, C33=22e-9,
    R42=2.2e3, R43=2.2e3, R44=220e3, R45=220e3, C34=6.8e-9, C35=680e-12,
    Rbass=100e3, Rtreble=100e3, Rlomid=100e3, Rhimid=100e3,
    # [ENG] MASTER + output
    C36=2.2e-6, Rmaster=100e3, C37=2.2e-6, R47=1e3, R46=100e3,
    # series R in the mid/treble wiper legs: NOT on the schematic (0 = as drawn)
    RwLoMid=0.0, RwHiMid=0.0,
)

NGSPICE = shutil.which("ngspice") or "ngspice"
VDD_RAIL = 8.65   # +9 V after D3 (1N5817) drop, circuit.md


def _res(x):
    """A resistance that ngspice will accept (strictly positive)."""
    return max(float(x), 1e-3)


def build_netlist(P=None, *, rails=None, attack="flat", grunt="cut", blend=0.0, level_R=(50e3, 50e3),
                  drive_R=50e3, master_R=(0.0, 100e3), bass=0.5, treble=0.5, lomid=0.5,
                  himid=0.5, gbw=3e6, stim="ac", stim_args="", sections=None,
                  inverter="mos", jfet_model=None, extra=""):
    """Return an ngspice netlist string.

    level_R  = (R_top, R_bottom) of the LEVEL pot: top = IC4_A out (pin 3), bottom = VD (pin 1).
    drive_R  = resistance between DRIVE pin 3 and wiper/pin 1 (the rheostat), 0..100k.
    master_R = (R_top, R_bottom) of the [ENG] MASTER pot; (0, 100k) = full CW = unity.
    """
    p = dict(DRAWN)
    if P:
        p.update(P)
    g = lambda k: p[k]

    L = []
    a = L.append
    a("* B7K as drawn -- generated by analysis/spice_reference/b7k_spice.py")
    a(".option reltol=1e-4 abstol=1e-12 vntol=1e-7 gmin=1e-12 method=gear")
    a(f"Vcc v9 0 DC {VDD_RAIL}")
    a("Vd vd 0 DC 4.5")
    if stim == "ac":
        a("Vin in 0 DC 0 AC 1")
    else:
        a(f"Vin in 0 {stim_args}")

    # ---- op-amp subckt: single-pole VCVS, inp inn out ------------------------------------
    A0 = 2e5
    if rails is not None:
        lo, hi = rails
        fp = (gbw or 1e12) / A0
        a(f".subckt opa inp inn out\nEg o1 0 inp inn {A0}\nRp o1 o2 1k\nCp o2 0 {1/(2*np.pi*1e3*fp)}\n"
          f"Bo out 0 V='min(max(V(o2),{lo}),{hi})'\n.ends")
    elif gbw is None:
        a(f".subckt opa inp inn out\nEg o1 0 inp inn {A0}\nRp o1 o2 1k\nCp o2 0 {1/(2*np.pi*1e3*1e5)}\n"
          f"Eo out 0 o2 0 1\n.ends")
    else:
        fp = gbw / A0
        a(f".subckt opa inp inn out\nEg o1 0 inp inn {A0}\nRp o1 o2 1k\nCp o2 0 {1/(2*np.pi*1e3*fp)}\n"
          f"Eo out 0 o2 0 1\n.ends")

    # ---- input + IC1_A ----------------------------------------------------------------
    a(f"R1 in 0 {g('R1')}")
    a(f"C1 in n1 {g('C1')}")
    a(f"R2 n1 vd {g('R2')}")
    a(f"R3 n1 ibp {g('R3')}")
    a("X1 ibp buf buf opa")

    # ---- JFET stage -------------------------------------------------------------------
    jm = jfet_model or ("J201 NJF(VTO=-0.718 BETA=1.031m LAMBDA=2m IS=114.5f RD=1 RS=1 "
                        "CGD=4.667p CGS=2.992p M=.2271 PB=.5 FC=.5)")
    a(f".model {jm}")
    a(f"C2 buf g1c {g('C2')}")
    a(f"R4 g1c q1g {g('R4')}")
    a(f"R5 q1g 0 {g('R5')}")
    a("J1 outg q1g q1s J201")
    a(f"R6 q1s 0 {g('R6')}")
    a(f"C3 q1s 0 {g('C3')}")
    a("J2 v9 q2g outg J201")
    a(f"R9 v9 q2g {g('R9')}")
    a(f"R10 q2g 0 {g('R10')}")
    a(f"C4 q2g outg {g('C4')}")

    # ---- treble ladder + ATTACK + DRIVE ---------------------------------------------------
    a(f"R7 outg m {g('R7')}")
    a(f"R8 m p {g('R8')}")
    a(f"C5 outg l1 {g('C5')}")
    a(f"C9 l1 l2 {g('C9')}")
    a(f"C6 l2 m {g('C6')}")
    a(f"R12 l1 0 {g('R12')}")
    a(f"R14 l2 0 {g('R14')}")
    a(f"C8 p c8b {g('C8')}")
    if attack == "boost":
        a("Rsw1 c8b m 1m")
    elif attack == "cut":
        a("Rsw1 c8b 0 1m")
    elif attack == "flat":
        a("Rsw1 c8b c8f 1e12\nRsw2 c8f 0 1e12")   # pole floating (tiny leak keeps DC defined)
    else:
        raise ValueError(attack)
    a(f"R11 p 0 {g('R11')}")
    a(f"C7 p q {g('C7')}")
    a(f"R13 q vd {g('R13')}")
    a("X2 q fb2 out2 opa")
    a(f"R15 out2 fb2 {g('R15')}")
    a(f"C10 out2 fb2 {g('C10')}")
    a(f"R17 fb2 dr3 {g('R17')}")
    a(f"Rdrv dr3 dr1 {_res(drive_R)}")
    a(f"R32 dr1 vd {g('R32')}")

    # ---- GRUNT + CMOS clipper -----------------------------------------------------------
    a(f"C11 out2 wr {g('C11')}")
    if grunt == "flat":
        a(f"C12 out2 wr {g('C12')}")
    elif grunt == "boost":
        a(f"C13 out2 wr {g('C13')}")
    elif grunt != "cut":
        raise ValueError(grunt)
    a(f"R16 wr w {g('R16')}")
    a(".model D4148 D(IS=2.52n N=1.752 RS=0.568 CJO=4p)")
    a("D1 w v9 D4148")
    a("D2 0 w D4148")
    if inverter == "mos":
        # DAFx-2020 fitted Shichman-Hodges pair. Their alpha is the SPICE level-1 KP*W/L (Id_sat = alpha/2 (vGS-vT)^2);
        # that convention reproduces docs/nonlinear-component-modeling.md / circuit.md's derived VDD = 5.636 V,
        # I = 3.01 mA, Vm = 2.657 V (checked in analysis/spice_reference/check_inverter.py). lambda on the p-ch only
        a(".model NMD NMOS(LEVEL=1 VTO=1.5702 KP=5.1021e-3 LAMBDA=0 GAMMA=0)")
        a(".model PMD PMOS(LEVEL=1 VTO=-0.48476 KP=8.2246e-4 LAMBDA=0.06 GAMMA=0)")
        a(f"R19 v9 vddc {g('R19')}")
        a("MN co w 0 0 NMD W=1u L=1u")
        a("MP co w vddc vddc PMD W=1u L=1u")
    else:
        raise ValueError(inverter)
    a(f"R18 co w {g('R18')}")
    a(f"C14 co w {g('C14')}")
    a(f"C15 co c15b {g('C15')}")
    a(f"R20 c15b bp {g('R20')}")
    a(f"R21 bp vd {g('R21')}")
    a("X3 bp bo bo opa")                      # IC2_B unity buffer
    a(f"C16 bo no {g('C16')}")
    a(f"R22 bo nm {g('R22')}")
    a(f"R23 nm no {g('R23')}")
    a(f"C17 nm 0 {g('C17')}")
    a(f"R24 no n1sk {g('R24')}")
    a(f"R25 n1sk k2p {g('R25')}")
    a(f"C27 k2p 0 {g('C27')}")
    a(f"C18 n1sk skbo {g('C18')}")
    a("X4 k2p skbo skbo opa")                 # IC4_B
    a(f"R26 skbo n2sk {g('R26')}")
    a(f"R27 n2sk k3p {g('R27')}")
    a(f"C20 k3p 0 {g('C20')}")
    a(f"C19 n2sk skao {g('C19')}")
    a("X5 k3p skao skao opa")                 # IC4_A

    # ---- LEVEL / BLEND ------------------------------------------------------------------
    a(f"Rlv1 skao lvw {_res(level_R[0])}")
    a(f"Rlv2 lvw vd {_res(level_R[1])}")
    a(f"Rbl1 lvw mix {_res((1.0 - blend) * g('Rblend'))}")
    a(f"Rbl2 mix buf {_res(blend * g('Rblend'))}")

    # ---- EQ: IC5_A buffer, IC5_B -2.2x, C21, Baxandall (IC5_C) ----------------------------
    a("X6 mix a1o a1o opa")
    a(f"R28 a1o bin {g('R28')}")
    a("X7 vd bin bout opa")
    a(f"R29 bout bin {g('R29')}")
    a(f"C21 bout tsin {g('C21')}")
    # bass pot: lug3 = A, lug1 = B ; wiper at fraction (1 - knob) from lug3
    rb = g("Rbass")
    a(f"R33 tsin A {g('R33')}")
    a(f"Rb3 A Wb {_res((1.0 - bass) * rb)}")
    a(f"Rb1 Wb B {_res(bass * rb)}")
    a(f"R34 B bxo {g('R34')}")
    a(f"C25 A Wb {g('C25')}")
    a(f"C26 Wb B {g('C26')}")
    a(f"R35 Wb vsum {g('R35')}")
    # treble pot: lug3 = T3 via C28 from tsin, lug1 = T1 via C29 to bxo
    rt = g("Rtreble")
    a(f"C28 tsin T3 {g('C28')}")
    a(f"Rt3 T3 Wt {_res((1.0 - treble) * rt)}")
    a(f"Rt1 Wt T1 {_res(treble * rt)}")
    a(f"C29 T1 bxo {g('C29')}")
    a(f"R36 Wt vsum {g('R36')}")
    a("X8 vd vsum bxo opa")                   # IC5_C
    a(f"R37 vsum bxo {g('R37')}")
    a(f"C30 vsum bxo {g('C30')}")
    # ---- LO-MID ---------------------------------------------------------------------------
    a(f"C31 bxo lmin {g('C31')}")
    a(f"R38 lmin lm3 {g('R38')}")
    a(f"R39 lm1 lmo {g('R39')}")
    a(f"R41 lmin lmm {g('R41')}")
    a(f"R40 lmm lmo {g('R40')}")
    rl = g("Rlomid")
    a(f"Rl3 lm3 lmw {_res((1.0 - lomid) * rl)}")
    a(f"Rl1 lmw lm1 {_res(lomid * rl)}")
    a(f"C32 lm3 lm1 {g('C32')}")
    if g("RwLoMid") > 0:
        a(f"Rwl lmw lmwc {g('RwLoMid')}")
        a(f"C33 lmwc lmm {g('C33')}")
    else:
        a(f"C33 lmw lmm {g('C33')}")
    a("X9 vd lmm lmo opa")                    # IC5_D
    # ---- HI-MID ---------------------------------------------------------------------------
    a(f"R42 lmo hm3 {g('R42')}")
    a(f"R43 hm1 hmo {g('R43')}")
    a(f"R44 lmo hmm {g('R44')}")
    a(f"R45 hmm hmo {g('R45')}")
    rh = g("Rhimid")
    a(f"Rh3 hm3 hmw {_res((1.0 - himid) * rh)}")
    a(f"Rh1 hmw hm1 {_res(himid * rh)}")
    a(f"C34 hm3 hm1 {g('C34')}")
    if g("RwHiMid") > 0:
        a(f"Rwh hmw hmwc {g('RwHiMid')}")
        a(f"C35 hmwc hmm {g('C35')}")
    else:
        a(f"C35 hmw hmm {g('C35')}")
    a("X10 vd hmm hmo opa")                   # IC6_A
    # ---- [ENG] MASTER + output ------------------------------------------------------------
    a(f"C36 hmo mt {g('C36')}")
    a(f"Rm1 mt mw {_res(master_R[0])}")
    a(f"Rm2 mw vd {_res(master_R[1])}")
    a("X11 mw o6 o6 opa")                     # IC6_B
    a(f"C37 o6 outn {g('C37')}")
    a(f"R46 outn 0 {g('R46')}")
    a(f"R47 outn out {g('R47')}")
    a("Rload out 0 1G")
    if extra:
        a(extra)
    return "\n".join(L) + "\n"


def run_ac(netlist, nodes, f0=10.0, f1=40e3, ppd=60):
    """AC sweep; return (freqs, {node: complex array}).  Node 0 = ground."""
    tmp = tempfile.mkdtemp(prefix="b7k_spice_")
    try:
        cir = os.path.join(tmp, "c.cir")
        dat = os.path.join(tmp, "o.dat")
        ctl = [".ac dec %d %g %g" % (ppd, f0, f1), ".control", "run"]
        for n in nodes:
            ctl.append("print vr(%s) vi(%s) > /dev/null" % (n, n))
        ctl.append("set wr_vecnames")
        ctl.append("set wr_singlescale")
        ctl.append("option numdgt=12")
        ctl.append("wrdata %s %s" % (dat, " ".join("v(%s)" % n for n in nodes)))
        ctl.append("quit")
        ctl.append(".endc")
        with open(cir, "w") as f:
            f.write(netlist + "\n".join(ctl) + "\n.end\n")
        r = subprocess.run([NGSPICE, "-b", cir], capture_output=True, text=True, timeout=600)
        if not os.path.exists(dat):
            raise RuntimeError("ngspice failed:\n" + r.stdout[-3000:] + r.stderr[-2000:])
        raw = np.loadtxt(dat, skiprows=1)
        # wrdata + wr_singlescale: freq, then (re, im) per vector
        freqs = raw[:, 0]
        out = {}
        for i, n in enumerate(nodes):
            re_, im_ = raw[:, 1 + 2 * i], raw[:, 2 + 2 * i]
            out[n] = re_ + 1j * im_
        return freqs, out
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def clipper_netlist(P=None, grunt="cut", stim_args="SIN(0 0.1 440)", inverter="mos", vdd=VDD_RAIL, diodes=True):
    """GRUNT bank + R16 + CD4049 (two-MOSFET) + R19 supply dropper, driven by an IDEAL source at the
    IC2_A output (node `out2`).  Output node `co` is the inverter output.  Used for the large-signal
    comparison against the plugin's Clipper (which is a fitted VTC, not this device model)."""
    p = dict(DRAWN)
    if P:
        p.update(P)
    L = ["* B7K clipper only (drawn values)", ".option reltol=1e-5 abstol=1e-12 vntol=1e-8 gmin=1e-12 method=gear",
         f"Vcc v9 0 DC {vdd}", f"Vsrc out2 0 {stim_args}",
         f"C11 out2 wr {p['C11']}"]
    if grunt == "flat":
        L.append(f"C12 out2 wr {p['C12']}")
    elif grunt == "boost":
        L.append(f"C13 out2 wr {p['C13']}")
    L += [f"R16 wr w {p['R16']}"]
    if diodes:
        L += [".model D4148 D(IS=2.52n N=1.752 RS=0.568 CJO=4p)", "D1 w v9 D4148", "D2 0 w D4148"]
    L += [".model NMD NMOS(LEVEL=1 VTO=1.5702 KP=5.1021e-3 LAMBDA=0 GAMMA=0)",
          ".model PMD PMOS(LEVEL=1 VTO=-0.48476 KP=8.2246e-4 LAMBDA=0.06 GAMMA=0)",
          f"R19 v9 vddc {p['R19']}", "MN co w 0 0 NMD W=1u L=1u", "MP co w vddc vddc PMD W=1u L=1u",
          f"R18 co w {p['R18']}", f"C14 co w {p['C14']}"]
    return "\n".join(L) + "\n"


def run_tran(netlist, nodes, tstop, tstep, tstart=0.0):
    """Transient; returns (t, {node: v}) resampled on the ngspice output grid."""
    tmp = tempfile.mkdtemp(prefix="b7k_tran_")
    try:
        cir = os.path.join(tmp, "c.cir")
        dat = os.path.join(tmp, "o.dat")
        ctl = [f".tran {tstep} {tstop} {tstart} {tstep}", ".control", "run", "set wr_vecnames",
               "set wr_singlescale", "option numdgt=10",
               "wrdata %s %s" % (dat, " ".join("v(%s)" % n for n in nodes)), "quit", ".endc"]
        with open(cir, "w") as f:
            f.write(netlist + "\n".join(ctl) + "\n.end\n")
        r = subprocess.run([NGSPICE, "-b", cir], capture_output=True, text=True, timeout=1200)
        if not os.path.exists(dat):
            raise RuntimeError("ngspice failed:\n" + r.stdout[-3000:] + r.stderr[-2000:])
        raw = np.loadtxt(dat, skiprows=1)
        t = raw[:, 0]
        return t, {n: raw[:, 1 + i] for i, n in enumerate(nodes)}
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    nl = build_netlist(gbw=None, blend=0.0)
    f, o = run_ac(nl, ["out", "buf", "bxo"])
    H = o["out"]
    for fr in (20, 100, 1000, 10000):
        i = np.argmin(abs(f - fr))
        print("%7.0f Hz  |H|=%7.3f dB" % (f[i], 20 * np.log10(abs(H[i]))))
