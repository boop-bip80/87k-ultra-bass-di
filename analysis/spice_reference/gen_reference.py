#!/usr/bin/env python3
"""Regenerate tests/data/schematic_reference.h from ngspice (the committed gate data for
tests/SchematicParityTest.cpp).  Run after changing b7k_spice.py; needs ngspice on PATH.

Conventions (must match the test): all pots in the plugin's knob space; spice side uses the drawn
values (C21 = 100n, mid caps as drawn, R36 = 3k3, no series wiper R) and ideal op-amps; the OD cases are
BLEND = 100 % OD, LEVEL max, MASTER max, EQ flat, ATTACK flat; the clipper cases use the SIMPLE
two-MOSFET device model (the one ngspice's LEVEL=1 MOSFET reproduces exactly)."""
import os
import sys
import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from b7k_spice import build_netlist, run_ac, clipper_netlist, run_tran
from compare_clipper import harmonics
from compare_chain import spice_case as chain_spice_case, KIN

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "data", "schematic_reference.h")
CLEAN_F = [31.0, 62.0, 125.0, 250.0, 500.0, 1000.0, 2000.0, 4000.0]
OD_F = [40.0, 80.0, 160.0, 640.0, 1000.0, 2000.0, 4000.0]
CLEAN = [  # name, bass, treble, lomid, himid
    ("flat", .5, .5, .5, .5), ("bass_boost", 1.0, .5, .5, .5), ("bass_cut", 0.0, .5, .5, .5),
    ("treble_boost", .5, 1.0, .5, .5), ("lomid_cut", .5, .5, 0.0, .5), ("himid_boost", .5, .5, .5, 1.0),
    ("all_boost", 1.0, 1.0, 1.0, 1.0),
]
OD = [("cut", 0.0), ("cut", 0.5), ("flat", 0.0), ("flat", 0.5), ("boost", 0.0)]
DRIVE_P = 1.98


def db_at(f, H, freqs):
    mag = 20 * np.log10(np.abs(H))
    return [float(np.interp(np.log(x), np.log(f), mag)) for x in freqs]


def main():
    L = ["// GENERATED by analysis/spice_reference/gen_reference.py -- do not edit by hand.",
         "// ngspice of the drawn schematic (see b7k_spice.py). dB gains, chain volts per input volt.",
         "#pragma once", "namespace schematic_ref {"]
    L.append("struct Freqs { static constexpr int nClean = %d, nOd = %d; };" % (len(CLEAN_F), len(OD_F)))
    L.append("static const double cleanF[] = {%s};" % ", ".join(repr(x) for x in CLEAN_F))
    L.append("static const double odF[] = {%s};" % ", ".join(repr(x) for x in OD_F))
    L.append("struct CleanCase { const char* name; double bass, treble, lomid, himid; double db[%d]; };" % len(CLEAN_F))
    L.append("static const CleanCase clean[] = {")
    for name, b, t, lm, hm in CLEAN:
        nl = build_netlist(blend=0.0, gbw=None, bass=b, treble=t, lomid=lm, himid=hm)
        f, o = run_ac(nl, ["out"], f0=10, f1=30e3, ppd=120)
        L.append('  {"%s", %g, %g, %g, %g, {%s}},' % (name, b, t, lm, hm, ", ".join("%.4f" % x for x in db_at(f, o["out"], CLEAN_F))))
    L.append("};")
    L.append("struct OdCase { const char* grunt; double drive; double db[%d]; };" % len(OD_F))
    L.append("static const OdCase od[] = {")
    for g, d in OD:
        nl = build_netlist(blend=1.0, level_R=(0.0, 100e3), drive_R=100e3 * (1 - d) ** DRIVE_P, grunt=g, gbw=None)
        f, o = run_ac(nl, ["out"], f0=10, f1=30e3, ppd=120)
        L.append('  {"%s", %g, {%s}},' % (g, d, ", ".join("%.4f" % x for x in db_at(f, o["out"], OD_F))))
    L.append("};")
    # clipper: simple two-MOSFET device model, ideal sine at the DRIVE-stage output
    CL = [("cut", 1000.0, 0.03), ("cut", 1000.0, 0.3), ("cut", 1000.0, 3.0),
          ("flat", 200.0, 0.1), ("flat", 200.0, 1.0), ("boost", 200.0, 0.03), ("boost", 200.0, 0.3)]
    L.append("struct ClipCase { const char* grunt; double freq, amp, pp, h[7]; };")
    L.append("static const ClipCase clip[] = {")
    for g, fq, amp in CL:
        nl = clipper_netlist(grunt=g, stim_args=f"SIN(0 {amp} {fq})")
        t, o = run_tran(nl, ["co"], tstop=0.05, tstep=1e-6, tstart=0.03)
        mags, pp = harmonics(t, o["co"], fq)
        L.append('  {"%s", %g, %g, %.4f, {%s}},' % (g, fq, amp, pp, ", ".join("%.3f" % (20 * np.log10(m + 1e-30)) for m in mags)))
    L.append("};")
    # end-to-end large signal (BLEND = OD, LEVEL/MASTER max, EQ flat, GRUNT cut, drive 0.5, 440 Hz), op-amps clamped
    # to the plugin's rail window; the plugin side must use clipPhysical = 1 (the simple model ngspice runs)
    L.append("struct ChainCase { double freq, drive, ampV; double h[5]; };")
    L.append("static const ChainCase chain[] = {")
    for dbfs in (-30, -24, -18, -12, -6):
        amp = KIN * 10 ** (dbfs / 20)
        m = chain_spice_case((440.0, amp, 0.5, "cut", 2.9, 2.7))
        L.append("  {440.0, 0.5, %.6f, {%s}}," % (amp, ", ".join("%.3f" % (20 * np.log10(x + 1e-30)) for x in m[:5])))
    L.append("};")
    L.append("} // namespace schematic_ref")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
